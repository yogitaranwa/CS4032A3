"""Turn the measured files in results/ into results/summary.md, results/cost.md and results/slo.json.

Only reads files that exist; nothing is estimated except the cost, which follows the formula in data/rate_card.json.
"""
import csv
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"


def parse_qty(q):
    q = str(q)
    if q.endswith("m"):
        return float(q[:-1]) / 1000
    for suf, mult in (("Gi", 1), ("Mi", 1 / 1024)):
        if q.endswith(suf):
            return float(q[:-2]) * mult
    return float(q)


def aggregated(path):
    for r in csv.DictReader(open(path, encoding="utf-8")):
        if r["Name"] == "Aggregated":
            return r
    raise SystemExit(f"no Aggregated row in {path}")


def cost(rate_card, deployment, stats):
    c = deployment["spec"]["template"]["spec"]["containers"][0]["resources"]["limits"]
    replicas = deployment["spec"]["replicas"]
    cpu, mem = parse_qty(c["cpu"]), parse_qty(c["memory"])
    hourly_replica = cpu * rate_card["vcpu_hour"] + mem * rate_card["gib_memory_hour"]
    hourly = replicas * hourly_replica
    rps = float(stats["Requests/s"])
    per_hour = rps * 3600
    per_1000 = hourly / per_hour * 1000
    return dict(replicas=replicas, cpu=cpu, mem=mem, hourly_replica=hourly_replica, hourly=hourly, rps=rps,
                per_hour=per_hour, per_1000=per_1000, rate_card=rate_card)


def cost_md(x):
    rc = x["rate_card"]
    return f"""# Cost estimate for 1,000 requests (estimated, no real charge)

Rates from data/rate_card.json: {rc['vcpu_hour']} {rc['currency']} per vCPU-hour, {rc['gib_memory_hour']} {rc['currency']} per GiB-hour.
Billing rule: every replica is billed for its CPU limit and memory limit for every hour it runs.

1. Limits per replica (k8s/app/deployment.yaml): {x['cpu']} vCPU, {x['mem']} GiB
2. Hourly cost per replica = {x['cpu']} x {rc['vcpu_hour']} + {x['mem']} x {rc['gib_memory_hour']} = {x['hourly_replica']:.4f} {rc['currency']}
3. Running replicas: {x['replicas']}, hourly cost of all replicas = {x['replicas']} x {x['hourly_replica']:.4f} = {x['hourly']:.4f} {rc['currency']}
4. Measured throughput (results/standard/loadtest_stats.csv): {x['rps']:.3f} requests/s
5. Requests served per hour = {x['rps']:.3f} x 3600 = {x['per_hour']:.1f}
6. Cost per 1,000 requests = {x['hourly']:.4f} / {x['per_hour']:.1f} x 1000 = **{x['per_1000']:.4f} {rc['currency']}**
"""


def main():
    lines = ["# Measured results (generated by scripts/summarize.py from results/)", ""]
    std = R / "standard" / "loadtest_stats.csv"
    if std.exists():
        a = aggregated(std)
        n, f = int(a["Request Count"]), int(a["Failure Count"])
        lines += ["## Standard load test (2 min, 4 users, via the Ingress)",
                  f"- requests: {n}, failures: {f}, error rate: {100 * f / max(n, 1):.3f}%",
                  f"- p50: {a['50%']} ms, p95: {a['95%']} ms, throughput: {a['Requests/s']} requests/s", ""]
        hdr = R / "standard" / "loadtest_headers.json"
        if hdr.exists():
            lines += ["- requests per replica / model version: `" + json.dumps(json.loads(hdr.read_text())) + "`", ""]
        deployment = yaml.safe_load((ROOT / "k8s" / "app" / "deployment.yaml").read_text())
        x = cost(json.loads((ROOT / "data" / "rate_card.json").read_text()), deployment, a)
        (R / "cost.md").write_text(cost_md(x), encoding="utf-8")
        budget = int(n * 0.01)
        slo = {"slo": "99% of requests succeed (HTTP 200 within 30 s)", "target_success_pct": 99,
               "window": "one standard load-test run (2 minutes)", "requests": n, "failed": f,
               "error_budget_requests": budget, "budget_used_requests": f,
               "budget_used_pct": round(100 * f / budget, 1) if budget else None}
        (R / "slo.json").write_text(json.dumps(slo, indent=2) + "\n", encoding="utf-8")
        lines += [f"## SLO\n- {slo['slo']}; window: {slo['window']}",
                  f"- error budget = 1% of {n} = {budget} requests; failures: {f} ({slo['budget_used_pct']}% of the budget used)", ""]
        lines += ["## Cost", f"- {x['per_1000']:.4f} {x['rate_card']['currency']} per 1,000 requests (steps in results/cost.md)", ""]
    for name, title in (("rollout", "Rolling update + rollback"), ("recovery", "Pod deletion recovery"),
                        ("hpa", "HPA run")):
        p = R / name / "failed.txt"
        if p.exists():
            lines += [f"## {title}", "- " + p.read_text().strip(), ""]
    cs = R / "coldstart" / "summary.json"
    if cs.exists():
        lines += ["## Cold start (Pod creation to Ready)", "```", cs.read_text().strip(), "```", ""]
    mem = R / "memtest" / "summary.txt"
    if mem.exists():
        lines += ["## 50 requests at 1 CPU / 1 GiB", "```", mem.read_text().strip(), "```", ""]
    for name in ("teacher", "base", "student_v1", "student_v2"):
        p = R / f"{name}_validation.json"
        if p.exists():
            d = json.loads(p.read_text())
            lines += [f"- {name}: validity {d['json_validity']}, intent {d['intent_accuracy']}, date {d['date_accuracy']}, "
                      f"time {d['time_accuracy']}, place {d['place_accuracy']}, full_frame {d['full_frame']}"]
    (R / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    sys.exit(main())
